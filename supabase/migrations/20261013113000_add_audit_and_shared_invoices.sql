create or replace function private.capture_audit_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  before_row jsonb;
  after_row jsonb;
  source_row jsonb;
begin
  if tg_op = 'INSERT' then
    before_row := null;
    after_row := to_jsonb(new);
    source_row := after_row;
  elsif tg_op = 'UPDATE' then
    before_row := to_jsonb(old);
    after_row := to_jsonb(new);
    source_row := after_row;
  else
    before_row := to_jsonb(old);
    after_row := null;
    source_row := before_row;
  end if;

  insert into public.audit_logs (
    owner_id,
    actor_user_id,
    actor_email,
    action,
    entity_type,
    entity_id,
    entity_label,
    old_values,
    new_values
  ) values (
    (source_row ->> 'owner_id')::uuid,
    auth.uid(),
    coalesce(auth.jwt() ->> 'email', current_user, 'sistema'),
    tg_op,
    tg_table_name,
    source_row ->> 'id',
    coalesce(source_row ->> tg_argv[0], ''),
    before_row,
    after_row
  );

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

revoke all on function private.capture_audit_change() from public, anon, authenticated;

create trigger stores_capture_audit
after insert or update or delete on public.stores
for each row execute function private.capture_audit_change('name');

create trigger equipment_types_capture_audit
