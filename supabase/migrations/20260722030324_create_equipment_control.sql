create table public.stores (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 160),
  state varchar(2) not null check (state ~ '^[A-Z]{2}$'),
  city text not null default '',
  address text not null default '',
  created_at timestamptz not null default now()
);

create table public.equipment_types (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 100),
  created_at timestamptz not null default now(),
  unique (owner_id, name)
);

create table public.equipments (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 200),
  equipment_type_id bigint not null references public.equipment_types(id) on delete restrict,
  store_id bigint not null references public.stores(id) on delete restrict,
  serial_number text not null check (char_length(trim(serial_number)) between 1 and 200),
  purchase_date date not null,
  purchase_value numeric(14,2) not null default 0 check (purchase_value >= 0),
  warranty_start date,
  warranty_end date,
  extended_warranty_end date,
  warranty_closed boolean not null default false,
  notes text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (owner_id, serial_number),
  check (warranty_end is null or warranty_start is null or warranty_end >= warranty_start),
  check (extended_warranty_end is null or warranty_end is null or extended_warranty_end >= warranty_end)
);

create table public.attachments (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  equipment_id bigint not null references public.equipments(id) on delete cascade,
  file_name text not null check (char_length(trim(file_name)) between 1 and 255),
  mime_type text not null check (mime_type in ('application/pdf', 'image/jpeg', 'image/png')),
  size_bytes bigint not null check (size_bytes >= 0),
  kind text not null check (kind in ('Nota fiscal', 'Garantia estendida')),
  storage_path text not null unique,
  created_at timestamptz not null default now()
);

create index stores_owner_idx on public.stores(owner_id);
create index equipment_types_owner_idx on public.equipment_types(owner_id);
create index equipments_owner_active_idx on public.equipments(owner_id, active);
create index equipments_store_idx on public.equipments(store_id);
create index equipments_type_idx on public.equipments(equipment_type_id);
create index equipments_purchase_date_idx on public.equipments(purchase_date);
create index equipments_warranty_end_idx on public.equipments(warranty_end);
create index attachments_owner_idx on public.attachments(owner_id);
create index attachments_equipment_idx on public.attachments(equipment_id);

create or replace function public.set_equipment_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger equipments_set_updated_at before update on public.equipments
for each row execute function public.set_equipment_updated_at();

